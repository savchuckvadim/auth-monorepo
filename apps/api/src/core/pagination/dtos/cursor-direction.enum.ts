/**
 * Направление обхода keyset-пагинированного списка (для обратно-скроллящихся
 * лент — сообщений, уведомлений). Для обычных лент (посты, users) не нужно —
 * достаточно `nextCursor`.
 */
export enum CursorDirection {
    /** Подгрузить записи старее курсора (скролл в прошлое). */
    OLDER = 'older',
    /** Подгрузить записи новее курсора (догнать live/catch-up). */
    NEWER = 'newer',
}
